"""Build aac-guides.js from content/aac/.

research/<subject>.json  multi-source research (expansive guide per stage, rules, mistakes, sources)
curated.json             the distilled full-marks checklist and panel layout per subject;
                         each curated stage lists the research stage indices it merges ("from").
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AAC = ROOT / "content" / "aac"


def build(subject, cur):
    res = json.loads((AAC / "research" / f"{subject}.json").read_text())
    stages = []
    for st in cur["stages"]:
        guide = [g for i in st["from"] for g in res["stages"][i]["guide"]]
        stages.append({k: st.get(k) for k in ("name", "marks", "marksNote", "checklist")} | {"guide": guide})
    # Rules and mistakes apply to the whole component, so they sit with the hand-in stage
    stages[-1]["guide"] += [
        {"h": "Rules you can't break", "points": res["rules"]},
        {"h": "Mistakes that cost marks", "points": res["mistakes"]},
    ]
    return {
        "subject": subject,
        "subjectTitle": cur["subjectTitle"],
        "title": cur.get("title") or res["title"],
        "weight": cur.get("weight") or res["weight"],
        "marks": cur.get("marks", res.get("marks")),
        "level": cur["level"],
        "summary": cur.get("summary") or res["summary"],
        "brief": cur["brief"],
        "stages": stages,
        "sources": [{"label": s["label"], "url": s["url"]} for s in res["sources"] if s.get("url", "").startswith("https://")],
    }


def main():
    curated = json.loads((AAC / "curated.json").read_text())
    guides = {subject: build(subject, cur) for subject, cur in curated.items()}
    out = ROOT / "aac-guides.js"
    out.write_text(
        "// Generated by scripts/build_aac_guides.py from content/aac/. Do not edit by hand.\n"
        f"window.AAC_GUIDES = {json.dumps(guides, ensure_ascii=False, indent=1)};\n"
    )
    for s, g in guides.items():
        print(f"{s}: {len(g['stages'])} stages, {sum(len(x['checklist']) for x in g['stages'])} steps, {len(g['sources'])} sources")


if __name__ == "__main__":
    main()
