"""Build grade-stats.js (and the static H1 table on the points calculator page) from the
State Examinations Commission's national Leaving Cert statistics.

    python3 scripts/build_grade_stats.py data/sec-statistics/lc-2026-provisional-national.csv

Source: examinations.ie/statistics -> year -> "Leaving Certificate <year> Provisional National
Statistics with more than 10 candidates (csv)". examinations.ie blocks plain HTTP clients, so
download it in a browser. The SEC publishes these statistics under CC BY 4.0
(data.gov.ie/organization/state-examinations-commission); the page credits them.

CSV columns: Code, Subject, Level (A = Higher, G = Ordinary, B = Foundation), Year, Total,
then the percentage of candidates at grades 1-8.
"""
import csv
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_JS = ROOT / "grade-stats.js"
PAGE = ROOT / "leaving-cert-points-calculator" / "index.html"
LEVELS = {"A": "H", "G": "O", "B": "F"}

# SEC subject name -> the name used in the calculator's subject list.
NAMES = {
    "PHYSICS & CHEMISTRY": "Physics and Chemistry",
    "HOME ECONOMICS S & S": "Home Economics",
    "DESIGN & COMMUNICATION": "Design and Communication Graphics",
    "MANDARIN CHINESE": "Mandarin Chinese",
}
TABLE_ROWS = 14  # biggest Higher Level subjects shown in the static table


def calc_name(sec: str) -> str:
    return NAMES.get(sec, sec.title().replace(" And ", " and "))


def main(path: str) -> None:
    subjects: dict = {}
    year = None
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            row = {k.strip(): (v or "").strip() for k, v in row.items() if k}
            level = LEVELS.get(row["Level"])
            if not level:
                continue
            year = int(row["Year"])
            pct = [float(row[str(g)]) for g in range(1, 9)]
            subjects.setdefault(calc_name(row["Subject"]), {})[level] = {"n": int(row["Total"]), "p": pct}

    data = {
        "year": year,
        "provisional": "provisional" in path.lower(),
        "source": "State Examinations Commission, Leaving Certificate national statistics",
        "sourceUrl": "https://www.examinations.ie/statistics/",
        "licence": "CC BY 4.0",
        "subjects": dict(sorted(subjects.items())),
    }
    OUT_JS.write_text(
        "// Leaving Cert grade distribution by subject and level, from the State Examinations\n"
        "// Commission's national statistics (CC BY 4.0). Generated by scripts/build_grade_stats.py;\n"
        "// do not edit by hand. p[i] = % of candidates who got grade i+1; n = candidates.\n"
        f"window.BB_GRADE_STATS = {json.dumps(data, separators=(',', ':'))};\n"
    )

    # Static, crawlable table: H1 rate for the biggest Higher Level subjects.
    higher = sorted(((name, lv["H"]) for name, lv in subjects.items() if "H" in lv), key=lambda x: -x[1]["n"])[:TABLE_ROWS]
    rows = "\n".join(
        f'            <tr><th scope="row">{html.escape(name)}</th><td>{s["n"]:,}</td><td>{s["p"][0]:.1f}%</td>'
        f'<td>{s["p"][0] + s["p"][1]:.1f}%</td><td>{sum(s["p"][:4]):.1f}%</td></tr>'
        for name, s in higher
    )
    page = PAGE.read_text()
    new, count = re.subn(
        r"(<!-- grade-table:start -->).*?(\s*<!-- grade-table:end -->)",
        lambda m: m.group(1) + "\n" + rows + m.group(2), page, flags=re.S,
    )
    if count != 1:
        sys.exit("grade-table markers not found in the points calculator page")
    new = re.sub(r"(<!-- grade-year -->)\d{4}(<!-- /grade-year -->)", rf"\g<1>{year}\g<2>", new)
    PAGE.write_text(new)
    print(f"wrote {OUT_JS.name}: {len(subjects)} subjects ({year}); table: {len(higher)} rows")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
