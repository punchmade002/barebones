// Shared by scripts/build_subject_index.ts (writes subject-index.js) and
// tests/subject-lazy-load.test.cjs (checks it is current and that lazy loading
// produces the same topics as loading everything up front).
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const ROOT = path.resolve(__dirname, "..");

function stripVersion(src) {
  return src.replace(/^\.\//, "").replace(/\?.*$/, "");
}

// A bare browser-like global, enough for the data files (no DOM is touched at load).
function createContext(extra = {}) {
  const context = { console, ...extra };
  context.window = context;
  context.globalThis = context;
  vm.createContext(context);
  return context;
}

function run(context, file) {
  vm.runInContext(fs.readFileSync(path.join(ROOT, file), "utf8"), context, { filename: file });
}

// The per-subject file lists, read from subject-packs.js itself.
function readPacks() {
  const context = createContext();
  run(context, "subject-packs.js");
  const packs = {};
  for (const [subjectId, files] of Object.entries(context.SubjectPacks.files)) {
    packs[subjectId] = files.map(stripVersion);
  }
  return packs;
}

// Everything loaded at once, as the app did before lazy loading.
function loadEager(packs = readPacks()) {
  const context = createContext();
  run(context, "data.js");
  Object.values(packs).flat().forEach((file) => run(context, file));
  run(context, "generated-notes-content.js");
  run(context, "subject-builder.js");
  return context;
}

// Only one subject's files, the way the lazy app loads them.
function loadSubjectLazily(subjectId, packs = readPacks()) {
  const context = createContext({ BB_LAZY_SUBJECTS: true });
  run(context, "data.js");
  run(context, "generated-notes-content.js");
  run(context, "subject-builder.js");
  packs[subjectId].forEach((file) => run(context, file));
  context.buildGeneratedNotes(subjectId);
  return context;
}

function buildChapters(context, subjectId) {
  context.__subjectId = subjectId;
  return JSON.parse(vm.runInContext("JSON.stringify(buildSubjectChapters(__subjectId))", context));
}

function courseChapters(context, subjectId) {
  context.__subjectId = subjectId;
  return JSON.parse(vm.runInContext(
    "JSON.stringify(COURSE_DATA.chapters.filter((c) => c.subject === __subjectId))",
    context,
  ));
}

// Each topic keeps its id, title and subsections, but only its first flashcard.
function buildIndex() {
  const packs = readPacks();
  const context = loadEager(packs);
  const index = {};
  for (const subjectId of Object.keys(packs)) {
    index[subjectId] = {
      chapters: buildChapters(context, subjectId).map((chapter) => ({
        id: chapter.id,
        title: chapter.title,
        learningOutcomes: chapter.learningOutcomes.map((lo) => ({
          id: lo.id,
          code: lo.code,
          title: lo.title,
          keyTerms: (lo.keyTerms || []).slice(0, 1),
          cardCount: (lo.keyTerms || []).length,
        })),
      })),
    };
  }
  return index;
}

function renderIndexFile(index) {
  const body = Object.entries(index)
    .map(([subjectId, data]) => `  ${JSON.stringify(subjectId)}: ${JSON.stringify(data)}`)
    .join(",\n");
  return [
    "// Generated by scripts/build_subject_index.ts. Do not edit by hand.",
    "// Every topic of every lazily loaded subject (subject-packs.js) with only its first",
    "// flashcard and a card count, so the app can open without downloading any notes.",
    "// Re-run after adding, removing or renaming topics or flashcards:",
    "//     deno run -A scripts/build_subject_index.ts",
    "window.SUBJECT_INDEX = {",
    body,
    "};",
    "",
  ].join("\n");
}

module.exports = {
  ROOT,
  readPacks,
  loadEager,
  loadSubjectLazily,
  buildChapters,
  courseChapters,
  buildIndex,
  renderIndexFile,
};
