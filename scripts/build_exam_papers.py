#!/usr/bin/env python3
"""Copy a subject's past papers and marking schemes into the app and list them for the archive.

The pipeline already downloads every paper from examinations.ie into
pipeline/_data/raw/<subject>/ (gitignored). This script copies them to
exam-papers/<subject>/, where the app serves them, and writes exam-papers.js, which the
Exam papers screen reads. The PDFs are not opened; everything comes from the file names.

    python3 scripts/build_exam_papers.py biology

Rebuilding one subject keeps the entries already in exam-papers.js for the others.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "pipeline" / "_data" / "raw"
OUT_DIR = ROOT / "exam-papers"
OUT_JS = ROOT / "exam-papers.js"

# The course each subject's students sit now. Any paper set before `firstExamined` was set on an
# earlier course and is tagged Old Course in the archive.
SUBJECTS = {
    "biology": {
        "course": "2025 specification",
        "firstExamined": 2027,
        # From 2019 the paper comes in two booklets; "PA" in the pipeline's file names is the
        # Sections A and B booklet, which is also the answerbook.
        "parts": {"PA": "Sections A & B", "": "Section C"},
        "partsFrom": 2019,
    },
}

NAME = re.compile(r"^(\d{4})-(higher|ordinary)(?:-([A-Z0-9]+))?-EV-(papers|scheme)\.pdf$")
LEVEL_ORDER = {"higher": 0, "ordinary": 1}


def build(subject_id: str) -> dict:
    cfg = SUBJECTS[subject_id]
    src = RAW / subject_id
    if not src.is_dir():
        sys.exit(f"No downloaded papers in {src}")
    dest = OUT_DIR / subject_id
    dest.mkdir(parents=True, exist_ok=True)

    papers = []
    for pdf in sorted(src.glob("*.pdf")):
        m = NAME.match(pdf.name)
        if not m:
            print(f"  skipped {pdf.name} (name not recognised)")
            continue
        year, level, part_code, kind = int(m[1]), m[2], m[3] or "", m[4]
        if kind == "scheme":
            label = "Marking scheme"
        elif year >= cfg.get("partsFrom", 9999):
            label = cfg["parts"].get(part_code, part_code)
        else:
            label = "Exam paper"
        slug = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
        name = f"{year}-{level}-{slug}.pdf"
        shutil.copyfile(pdf, dest / name)
        papers.append({
            "year": year,
            "level": level,
            "kind": kind,
            "label": label,
            "file": f"exam-papers/{subject_id}/{name}",
            "oldCourse": year < cfg["firstExamined"],
        })

    # Newest first; the booklets in exam order, then the marking scheme
    part_order = list(cfg.get("parts", {}).values())
    papers.sort(key=lambda p: (
        -p["year"], LEVEL_ORDER[p["level"]], p["kind"] == "scheme",
        part_order.index(p["label"]) if p["label"] in part_order else 0,
    ))
    return {"course": cfg["course"], "firstExamined": cfg["firstExamined"], "papers": papers}


def read_existing() -> dict:
    if not OUT_JS.exists():
        return {}
    text = OUT_JS.read_text()
    m = re.search(r"window\.EXAM_PAPERS = (\{.*\});", text, re.S)
    return json.loads(m[1]) if m else {}


def main() -> None:
    if len(sys.argv) != 2 or sys.argv[1] not in SUBJECTS:
        sys.exit(f"Usage: build_exam_papers.py <{'|'.join(SUBJECTS)}>")
    subject_id = sys.argv[1]
    archive = read_existing()
    archive[subject_id] = build(subject_id)
    body = json.dumps(archive, indent=2)
    OUT_JS.write_text(
        "// Generated by scripts/build_exam_papers.py — do not edit by hand.\n"
        f"window.EXAM_PAPERS = {body};\n"
    )
    n = len(archive[subject_id]["papers"])
    print(f"{subject_id}: {n} files copied to exam-papers/{subject_id}/, listed in exam-papers.js")


if __name__ == "__main__":
    main()
