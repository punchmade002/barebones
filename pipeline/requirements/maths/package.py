"""Split the maths Learn phase and practice lessons into one small package per skill, so a page loads only the skill it shows.

  python3 pipeline/requirements/maths/package.py    # after learn.py assemble / lessons.py assemble

Writes maths-skills/ at the site root:
  index.js       every skill for the skill list (title, level, chapter, order) and each package's version
  <id>.js        that skill's Learn phase and its first practice problem
  <id>.more.js   its other practice problems, loaded once the student starts practising
Each package's ?v= is a hash of its contents, so a browser never keeps an old copy after a rebuild.
The index's own ?v= is written into the script tags of maths-learn.html and maths-skill.html.
"""
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / 'maths-skills'
PAGES = [ROOT / 'maths-learn.html', ROOT / 'maths-skill.html']


def globals_in(path):
    """{name: value} for every `window.NAME = <json>;` line of a generated file (json.dumps never writes a raw newline)."""
    found = {}
    for line in path.read_text().splitlines():
        m = re.match(r'window\.(\w+) = (.*);$', line)
        if m:
            found[m[1]] = json.loads(m[2])
    return found


def write(name, js):
    (OUT / name).write_text(js)
    return hashlib.sha1(js.encode()).hexdigest()[:10]


def main():
    learn = globals_in(HERE / 'build/maths-learn.js')['MATHS_LEARN']
    built = globals_in(HERE / 'build/maths-lessons.js')
    lessons = built['MATHS_LESSONS']
    db = json.loads((HERE / 'skills.json').read_text())
    chapters = db['chapters']
    OUT.mkdir(exist_ok=True)
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))
    order = {c: k for k, c in enumerate(chapters)}
    index, written = [], set()
    for s in sorted(db['skills'], key=lambda s: (order[s['chapter']], s['rank'])):
        sid = s['id']
        assert sid in learn, f'{sid} has no Learn phase: run learn.py assemble'
        les = lessons.get(sid)
        head = {k: v for k, v in les.items() if k != 'problems'} | {'count': len(les['problems'])} if les else None
        pack = {'learn': learn[sid], 'lesson': head, 'problems': les['problems'][:1] if les else []}
        row = {'id': sid, 'title': s['title'], 'level': s['level'], 'grade': s['grade'], 'chapter': s['chapter'],
               'lesson': bool(les), 'v': write(f'{sid}.js', f'(window.MATHS_PACKS = window.MATHS_PACKS || {{}})[{dump(sid)}] = {dump(pack)};\n')}
        written.add(f'{sid}.js')
        if les and len(les['problems']) > 1:
            row['vm'] = write(f'{sid}.more.js', f'(window.MATHS_MORE = window.MATHS_MORE || {{}})[{dump(sid)}] = {dump(les["problems"][1:])};\n')
            written.add(f'{sid}.more.js')
        index.append(row)
    v = write('index.js', '// Maths skills, generated by pipeline/requirements/maths/package.py. Do not edit by hand.\n'
                          f'window.MATHS_INDEX = {dump({"chapters": chapters, "skills": index})};\n')
    written.add('index.js')
    for old in OUT.iterdir():          # a skill that was renamed or removed
        if old.name not in written:
            old.unlink()
    for page in PAGES:
        html = page.read_text()
        new = re.sub(r'maths-skills/index\.js(\?v=[\w]*)?"', f'maths-skills/index.js?v={v}"', html)
        assert 'maths-skills/index.js?v=' in new, f'{page.name} does not load maths-skills/index.js'
        page.write_text(new)
    sizes = sorted((p.stat().st_size, p.name) for p in OUT.glob('*.js') if p.name != 'index.js' and '.more' not in p.name)
    print(f'{len(index)} skills → maths-skills/ (index {(OUT / "index.js").stat().st_size // 1024} KB, '
          f'largest skill {sizes[-1][0] // 1024} KB, median {sizes[len(sizes) // 2][0] // 1024} KB)')


if __name__ == '__main__':
    main()
