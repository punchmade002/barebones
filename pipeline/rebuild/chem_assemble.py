"""Build chemistry-exam-questions.js from the rebuilt state, the audited old answers and the fill run.

    python3 pipeline/rebuild/chem_assemble.py <chem-fill workflow output.json>

Chemistry departs from the Biology pipeline (assemble.py) because its answers were not written from
the notes: they were checked against the marking scheme instead.
  - On-spec parts whose exact label has an audited old answer (chem_old_answers.py: two Haiku
    auditors against the scheme, Sonnet rewrite + re-check) ship that answer: kept / written.
  - Every other part, off-spec included, ships the chem-fill answer (Haiku from the scheme points,
    Sonnet for figure parts and any spot-check fix): written. Off-spec parts keep offSpec=true,
    so the app labels them and tests skip them.
  - Parts with no answer from either source are flagged and listed in the review file.
Same bank shape as assemble.py. notesRefs are the scan's loIds (the notes sections the part tests).
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from chem_fill_packages import DATA, lab, old_answers, order  # noqa: E402
from assemble import LEVEL_NAME, SUBJECTS  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def main(fill_path):
    raw = json.loads(Path(fill_path).read_text())
    fill = (raw.get('result') or raw)['answers']
    crops = json.loads((DATA / 'crops.json').read_text())
    cfg = SUBJECTS['chemistry']
    bank, review, sources = [], [], Counter()
    for f in sorted((DATA / 'state').glob('*.json'), key=lambda p: order(p.name.split('.')[0])):
        if f.name.endswith('.scan.json'):
            continue
        st = json.loads(f.read_text())
        key = st['key']
        scan = {p['label']: p for p in json.loads((DATA / 'state' / f'{key}.scan.json').read_text())['parts']}
        crop = crops[key]
        old = old_answers(key)
        parts = []
        for p in st['parts']:
            sp = scan.get(p['label'], {})
            L = lab(p['label'])
            model, status, source = '', 'flagged', ''
            if not p.get('offSpec') and L in old:
                model, source = old[L], 'audited'
                status = 'kept' if re.search(rf'^{re.escape(p["label"].replace(" ", ""))} \[kept\]',
                                             (DATA / 'old-answers' / f'{key}.txt').read_text(), re.M) else 'written'
            elif f'{key}|{p["label"]}' in fill:
                a = fill[f'{key}|{p["label"]}']
                model, status, source = a['model'], 'written', a['by']
            else:
                review.append(f'- {key} {p["label"]}: no answer\n  {p["text"][:300]}')
            sources[source or 'none'] += 1
            refs = p.get('loIds') or ([sp['chapterId']] if sp.get('chapterId') else [])
            parts.append({
                'label': p['label'],
                'marks': p['marks'],
                'model': model.strip(),
                'model_source': source,
                'answerStatus': status,
                'type': p['type'],
                'diagramRelation': p['diagramRelation'],
                'offSpec': bool(p.get('offSpec')),
                'notesRefs': refs if model else [],
                '_chapter': sp.get('chapterId', ''),
            })
        on_spec = [p['_chapter'] for p in parts if not p['offSpec'] and p['_chapter']] or [p['_chapter'] for p in parts if p['_chapter']]
        for p in parts:
            del p['_chapter']
        bank.append({
            'id': f'chemistry-pp-{key}',
            'subject': 'chemistry',
            'chapterId': Counter(on_spec).most_common(1)[0][0],
            'sectionId': f'{cfg["prefix"]}-section{crop["section"]}',
            'source': f'LC Chemistry {LEVEL_NAME[crop["level"]]} {crop["year"]} — Section {crop["section"]} — Q{crop["number"]}',
            'year': crop['year'],
            'level': crop['level'],
            'paper': '',
            'questionNumber': crop['number'],
            'legacy': True,
            'totalMarks': st.get('questionMarks') or cfg['default_marks'][crop['section']],
            'images': crop['images'],
            'parts': parts,
        })

    header = ('// Chemistry exam bank, rebuilt from the papers (pipeline/EXAM_BANK_REBUILD.md).\n'
              '// Each question is shown as crops of the original paper (images[]), never as\n'
              '// transcribed text. Every model answer was checked against the official marking\n'
              '// scheme (audited old answers, or new answers written from the scheme points and\n'
              '// spot-checked by Sonnet). Generated by pipeline/rebuild/chem_assemble.py; do not edit by hand.\n')
    body = json.dumps(bank, indent=1, ensure_ascii=False)
    assert not re.search(r'"(question|text)":', body), 'question text must never ship'
    (ROOT / 'chemistry-exam-questions.js').write_text(
        header + 'window.EXAM_QUESTIONS_DB = (window.EXAM_QUESTIONS_DB || []).concat(\n' + body + '\n);\n')
    out = ROOT / 'pipeline/_data/rebuild-review'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'chemistry.md').write_text('# Chemistry rebuild: parts with no answer\n\n' + '\n'.join(review) + '\n')
    statuses = Counter(p['answerStatus'] for q in bank for p in q['parts'])
    print(f'{len(bank)} questions, {sum(statuses.values())} parts: {dict(statuses)}; sources {dict(sources)}; '
          f'{len(review)} unanswered -> {out / "chemistry.md"}')


if __name__ == '__main__':
    main(sys.argv[1])
