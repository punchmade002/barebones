def build(pack,out,D):
    ids=re.findall(r'^\[([^\]]+)\]',open(B+'packs/'+pack).read().split('\nCANDIDATES')[0],re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',open(B+'packs/'+pack).read(),re.M))
    assert ids==list(D) or set(ids)==set(D),(set(ids)^set(D))
    o={}
    for i in ids:
        c,nn=D[i]
        for x in nn: assert x['id'] in allids and x['id']!=i,(i,x)
        o[i]={"cost":c,"needs":nn}
    json.dump(o,open(B+'point-links/'+out,'w'),ensure_ascii=False)
    print(len(o),sum(len(v['needs']) for v in o.values()),sum(v['cost']==2 for v in o.values()),sum(x['confidence']=='low' for v in o.values() for x in v['needs']))
