tg=src.split('CANDIDATES')[0]
ids=re.findall(r'^\[(chem24-s1\.[^\]]+)\]',tg,re.M)
res={}
for i in ids:
    k=i[len(P):]
    c,nd=D[k]
    res[i]={"cost":c,"needs":nd}
assert set(D)=={i[len(P):] for i in ids},(set(D)^{i[len(P):] for i in ids})
allids=set(re.findall(r'^\[([^\]]+)\]',src,re.M))
for i,v in res.items():
    for x in v['needs']:
        assert x['id'] in allids and x['id']!=i,x
