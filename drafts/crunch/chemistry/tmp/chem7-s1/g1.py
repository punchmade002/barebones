def run(pack,out,P_,R_):
    txt=open(D+'packs/'+pack).read()
    tg=txt.split('CANDIDATES')[0]
    tids=re.findall(r'^\[([^\]]+)\]',tg,re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',txt,re.M))
    d={}
    for s,c,n in R_:
        k=P_+s
        d[k]={'cost':c,'needs':[{'id':i,'strength':st,'why':w,'confidence':cf} for i,st,w,cf in n]}
    assert list(d)==tids,(set(tids)^set(d))
    for k,v in d.items():
        for n in v['needs']: assert n['id'] in allids and n['id']!=k,(k,n)
    json.dump(d,open(D+'point-links/'+out,'w'),indent=1)
    L=sum(len(v['needs']) for v in d.values())
    print(len(d),L,sum(v['cost']==2 for v in d.values()),sum(n['confidence']=='low' for v in d.values() for n in v['needs']))
if __name__=='__main__': run('chem7-s1.t1g1.txt','chem7-s1.t1g1.json',P,R)
