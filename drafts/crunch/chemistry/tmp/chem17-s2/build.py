def L(s):
    i,st,why,c=s.split('|'); return {"id":i,"strength":{'E':'essential','H':'helpful'}[st],"why":why,"confidence":{'h':'high','l':'low'}[c]}
def build(pack,out,spec,prefix):
    txt=open(D+'packs/'+pack).read()
    tgt=re.findall(r'^\[('+prefix+r'[^\]]*)\]',txt.split('CANDIDATES')[0],re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',txt,re.M))
    assert set(spec)==set(tgt) and len(tgt)==len(spec),(set(tgt)^set(spec))
    res={}
    for t in tgt:
        c,ls=spec[t]; ls=[L(x) for x in ls]
        for l in ls: assert l['id'] in allids and l['id']!=t,(t,l)
        res[t]={"cost":c,"needs":ls}
    json.dump(res,open(D+'point-links/'+out,'w'),ensure_ascii=False,indent=1)
    n=sum(len(v['needs']) for v in res.values())
    print(out,len(res),n,sum(v['cost']==2 for v in res.values()),sum(l['confidence']=='low' for v in res.values() for l in v['needs']))

