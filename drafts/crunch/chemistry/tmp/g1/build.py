def L(i,s,w,c='high'): return {"id":i,"strength":{'e':'essential','h':'helpful'}[s],"why":w,"confidence":c}
def run(name,data):
    txt=open(D+'packs/'+name+'.txt').read()
    tgt=txt.split('CANDIDATES')[0]
    tids=re.findall(r'^\[([^\]]+)\]',tgt,re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',txt,re.M))
    assert [d[0] for d in data]==tids,(set(tids)^set(d[0] for d in data))
    out={};n=0;c2=0;low=0
    for i,c,l in data:
        out[i]={"cost":c,"needs":l};n+=len(l);c2+=c==2
        for x in l:
            assert x['id'] in allids and x['id']!=i,x; low+=x['confidence']=='low'
    json.dump(out,open(D+'point-links/'+name+'.json','w'),ensure_ascii=False,indent=1)
    print(name,len(tids),n,c2,low)
