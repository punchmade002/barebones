def L(s):
    i,st,w,c=s.split('|'); return {"id":i,"strength":{'E':'essential','H':'helpful'}[st],"why":w,"confidence":{'h':'high','l':'low'}[c]}
def build(pack,out,spec):
    txt=open(D+'packs/'+pack).read()
    ids=set(re.findall(r'^\[([^\]]+)\]',txt,re.M))
    tgt=re.findall(r'^\[([^\]]+)\]',txt.split('CANDIDATES')[0],re.M)
    res={}
    for k,(c,ls) in spec:
        assert k not in res,k
        res[k]={"cost":c,"needs":[L(x) for x in ls]}
    assert list(res)==tgt,(set(tgt)-set(res),set(res)-set(tgt))
    for k,v in res.items():
        for n in v['needs']: assert n['id'] in ids and n['id']!=k,(k,n)
    json.dump(res,open(D+'point-links/'+out,'w'),indent=1,ensure_ascii=False)
    print(out,len(res),sum(len(v['needs']) for v in res.values()),sum(v['cost']==2 for v in res.values()),sum(n['confidence']=='low' for v in res.values() for n in v['needs']))
