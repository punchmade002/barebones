def check(pk,out):
    txt=open(B+'packs/'+pk+'.txt').read()
    tg=[m.group(1) for m in re.finditer(r'^\[([^\]]+)\]',txt.split('CANDIDATES')[0],re.M)]
    allids=set(m.group(1) for m in re.finditer(r'^\[([^\]]+)\]',txt,re.M))
    d=json.load(open(out))
    assert list(d)==tg,(set(tg)^set(d))
    for k,v in d.items():
        for n in v['needs']:
            assert n['id'] in allids and n['id']!=k,(k,n)
    links=sum(len(v['needs']) for v in d.values()); low=sum(n['confidence']=='low' for v in d.values() for n in v['needs'])
    print(pk,len(d),links,sum(v.get('cost')==2 for v in d.values()),low)
