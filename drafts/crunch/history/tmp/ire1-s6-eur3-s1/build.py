import json,re,sys
D='/Users/gabrielwhelan/barebones/drafts/crunch/history/'
def build(pack,out,spec):
    txt=open(D+'packs/'+pack).read()
    tgt=[];allids=set();sec=None
    for l in txt.splitlines():
        if l.startswith('TARGET'):sec='t'
        elif l.startswith('CANDIDATES'):sec='c'
        m=re.match(r'\[([^\]]+)\]',l)
        if m:
            allids.add(m.group(1))
            if sec=='t':tgt.append(m.group(1))
    res={}
    for k,(c,needs) in spec.items():
        res[k]={'cost':c,'needs':[{'id':n[0],'strength':{'E':'essential','H':'helpful'}[n[1]],'why':n[2],'confidence':{'h':'high','l':'low'}[n[3]]} for n in needs]}
    assert list(res)==tgt,(set(tgt)-set(res),set(res)-set(tgt))
    for k,v in res.items():
        for n in v['needs']:
            assert n['id'] in allids and n['id']!=k,(k,n)
            assert len(n['why'].split())<=8
    json.dump(res,open(D+'point-links/'+out,'w'),indent=1)
    links=sum(len(v['needs']) for v in res.values())
    print(out,len(res),links,sum(v['cost']==2 for v in res.values()),sum(n['confidence']=='low' for v in res.values() for n in v['needs']))
