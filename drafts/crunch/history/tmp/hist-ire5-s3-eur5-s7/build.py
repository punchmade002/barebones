def run(pk,out,data):
    txt=open(B+'packs/'+pk).read()
    tg=txt.split('CANDIDATES')[0]
    tids=re.findall(r'^\[([^\]]+)\]',tg,re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',txt,re.M))
    assert [t for t,_,_ in data]==tids,(set(tids)^set(t for t,_,_ in data))
    res={}
    for t,c,n in data:
        for x in n: assert x[0] in allids and x[0]!=t,x
        res[t]={"cost":c,"needs":[{"id":a,"strength":b,"why":w,"confidence":cf} for a,b,w,cf in n]}
    json.dump(res,open(B+'point-links/'+out,'w'),indent=1)
    ls=sum(len(v['needs']) for v in res.values())
    print(out,len(res),ls,sum(v['cost']==2 for v in res.values()),sum(n['confidence']=='low' for v in res.values() for n in v['needs']))
