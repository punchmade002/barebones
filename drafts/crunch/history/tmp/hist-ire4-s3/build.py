def run(sub,S):
    t=open(D+f'packs/hist-ire4-{sub}.t1g1.txt').read()
    ids=re.findall(r'^\[(hist-ire4-%s\.[^\]]+)\]'%sub,t.split('CANDIDATES')[0],re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',t,re.M))
    out={}
    for i in ids:
        c,n=S[i.split('.',1)[1]]
        for x in n: assert x['id'] in allids and x['id']!=i,(i,x)
        out[i]={'cost':c,'needs':n}
    assert len(S)==len(ids),(len(S),len(ids))
    json.dump(out,open(D+f'point-links/hist-ire4-{sub}.t1g1.json','w'),indent=1)
    v=out.values()
    print(sub,len(ids),sum(len(x['needs']) for x in v),sum(x['cost']==2 for x in v),sum(n['confidence']=='low' for x in v for n in x['needs']))
