import json,re,sys
H='/Users/gabrielwhelan/barebones/drafts/crunch/history/'
E,P='essential','helpful'
def run(pack,out,pre,spec):
    txt=open(H+'packs/'+pack).read()
    tgt=txt.split('CANDIDATES')[0]
    tids=re.findall(r'^\[([^\]]+)\]',tgt,re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',txt,re.M))
    res={}
    for k,(c,ls) in spec.items():
        res[pre+k]={'cost':c,'needs':[{'id':i,'strength':s,'why':w,'confidence':cf} for i,s,w,cf in ls]}
    assert list(res)==tids,(set(tids)-set(res),set(res)-set(tids))
    n=0;low=0
    for k,v in res.items():
        for x in v['needs']:
            assert x['id'] in allids and x['id']!=k,x
            n+=1;low+=x['confidence']=='low'
    json.dump(res,open(H+'point-links/'+out,'w'),indent=1)
    json.load(open(H+'point-links/'+out))
    print(pack,len(res),n,sum(v['cost']==2 for v in res.values()),low)
