def out(S,pre,cand_files,path,costs=True):
    pk=open(D+'packs/'+cand_files).read()
    ids=re.findall(r'^\[([^\]]+)\]',pk,re.M)
    tg=[i for i in ids if i.startswith(pre)]
    res={}
    for k,(c,n) in S.items():
        r={'cost':c,'needs':[{'id':i,'strength':st,'why':w,'confidence':cf} for i,st,w,cf in n]}
        res[pre+k]=r
    assert list(res)==tg,(set(tg)^set(res))
    for r in res.values():
        for n in r['needs']:assert n['id'] in ids and n['id']!=None
    json.dump(res,open(path,'w'),indent=0,ensure_ascii=False)
    print(len(res),sum(len(r['needs']) for r in res.values()),sum(r['cost']==2 for r in res.values()),sum(n['confidence']=='low' for r in res.values() for n in r['needs']))
