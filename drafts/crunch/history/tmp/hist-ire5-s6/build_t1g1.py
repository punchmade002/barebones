def run(pack,out,D):
    txt=open(base+'packs/'+pack).read()
    sec=txt.split('\nCANDIDATES')
    tgt=re.findall(r'^\[(hist-ire\d-[^\]]+)\]',sec[0],re.M)
    allids=set(re.findall(r'^\[([^\]]+)\]',txt,re.M))
    res={};nl=0;c2=0;lo=0
    for t in tgt:
        k=re.sub(r'^hist-ire\d-s','',t)
        c,ns=D[k]
        for n in ns:
            assert n[0] in allids and n[0]!=t,(t,n)
        res[t]={'cost':c,'needs':[{'id':n[0],'strength':n[1],'why':n[2],'confidence':n[3]} for n in ns]}
        nl+=len(ns);c2+=c==2;lo+=sum(n[3]=='low' for n in ns)
    assert set(D)=={re.sub(r'^hist-ire\d-s','',t) for t in tgt}
    json.dump(res,open(base+'point-links/'+out,'w'),indent=1)
    print(out,len(tgt),nl,c2,lo)
run('hist-ire5-s6.t1g1.txt','hist-ire5-s6.t1g1.json',D)
