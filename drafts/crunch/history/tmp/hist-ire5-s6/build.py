import json,re,sys
H='/Users/gabrielwhelan/barebones/drafts/crunch/history/'
def build(pack,out,pre,data):
    txt=open(H+'packs/'+pack).read()
    ids=re.findall(r'^\[([^\]]+)\]',txt,re.M)
    tgt=[i for i in ids if i.startswith(pre+'.')]
    res={}
    for k,(c,links) in data:
        k=pre+'.'+k
        assert k not in res
        res[k]={'cost':c,'needs':[{'id':(l[0] if l[0].startswith('hist-') else pre+'.'+l[0]),'strength':'essential' if l[1]=='e' else 'helpful','why':l[2],'confidence':'low' if len(l)>3 else 'high'} for l in links]}
    assert list(res)==tgt,(set(tgt)^set(res))
    for v in res.values():
        for n in v['needs']: assert n['id'] in ids and n['id'] not in(),n
    for k,v in res.items():
        for n in v['needs']: assert n['id']!=k
    json.dump(res,open(H+'point-links/'+out,'w'),indent=1)
    L=sum(len(v['needs']) for v in res.values())
    print(len(res),L,sum(v['cost']==2 for v in res.values()),sum(len(n)>0 and n['confidence']=='low' for v in res.values() for n in v['needs']))
